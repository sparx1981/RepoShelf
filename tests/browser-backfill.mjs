import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
import {browserBacklog,browserBacklogState} from '../lib/browser-backlog.mjs';
import {checkpointWriter} from '../scripts/browser-checkpoint.mjs';
import {recordDemoResult,demoCandidates,publicUrlGuard} from '../scripts/demo-health.mjs';
import {previewCandidates} from '../scripts/preview-schedule.mjs';
import {previewWorkers} from '../scripts/preview-workers.mjs';
const now=Date.parse('2026-10-05T12:00:00Z'),base={full:'test/demo',name:'Demo',demo:'https://example.com',stars:5};
assert.equal(browserBacklogState(base).demo,'never');
let r=base;
for(let i=0;i<3;i++)r=recordDemoResult(r,{kind:'temporary',reason:'access_restricted'},now+i*2*3600000);
assert.equal(browserBacklogState(r).demo,'repeated');
assert.equal(browserBacklogState(r).screenshot,'repeated');
assert.equal(browserBacklogState(r).reviewRecommended,true);
assert.match(browserBacklogState(r).reviewAdvice,/Open the demo manually/);
assert.equal(Date.parse(r.demoHealth.nextCheckAt)-Date.parse(r.demoHealth.attemptedAt),86400000);
assert.equal(previewCandidates([r],now+5*3600000,1).length,0);
assert.equal(demoCandidates([r],now+5*3600000,1).length,0);
const good=recordDemoResult(r,{kind:'working'},now+29*3600000);
assert.equal(good.demoHealth.consecutiveTemporaryFailures,0);
assert.equal(good.demoHealth.status,'working');
assert.equal(demoCandidates([good],now+29*3600000,1).length,0,'Capture validation prevents a duplicate health visit');
assert.equal(browserBacklogState({...r,demo:'https://different.example'}).demo,'never');
assert.equal(browserBacklog([base,r,{...base,availability:'unavailable'}]).demo.repeated,1);
assert.equal(previewCandidates([good],now+29*3600000,1).length,0,'Recent validation must not be revisited immediately for a screenshot');
const missing={...base,full:'test/missing'},refresh={...base,full:'test/featured',qualityPriority:true,previewAttemptAt:new Date(now-8*86400000).toISOString(),screenshots:[{kind:'demo',url:base.demo,capturedAt:new Date(now-8*86400000).toISOString()}]};
assert.equal(previewCandidates([refresh,missing],now,1)[0].full,missing.full,'Missing screenshot precedes routine featured refresh');
const retry=recordDemoResult({...base,full:'test/retry'},{kind:'temporary'},now-3*3600000);
const stale={...recordDemoResult({...base,full:'test/stale'},{kind:'working'},now-8*86400000),qualityPriority:true};
assert.equal(demoCandidates([stale,retry,missing],now,1)[0].full,missing.full,'Untouched validation comes before retries and routine refreshes');
assert.equal(demoCandidates([stale,retry],now,1)[0].full,retry.full,'Missing validation comes before routine refreshes');
const report={...stale,demoReport:{id:77}};
assert.equal(demoCandidates([missing,report],now,1)[0].full,report.full,'New broken-demo reports remain urgent');
const dns=publicUrlGuard({resolver:async()=>{throw Error('not found')}});
assert.equal((await dns.assess('https://unresolved.example')).reason,'dns_unresolved');assert.equal(await dns('https://unresolved.example'),false);
const privateDns=publicUrlGuard({resolver:async()=>[{address:'127.0.0.1'}]});
assert.equal((await privateDns.assess('https://private.example')).reason,'unsafe_target');assert.equal(await privateDns('https://private.example'),false);
const slowDns=publicUrlGuard({resolver:()=>new Promise(()=>{}),timeout:2});assert.equal((await slowDns.assess('https://slow.example')).reason,'dns_timeout');
let active=0,peak=0;const finished=[];
await previewWorkers(Array.from({length:12},(_,i)=>i),async i=>{active++;peak=Math.max(peak,active);await new Promise(r=>setTimeout(r,2));finished.push(i);active--},{concurrency:4});
assert.equal(peak,4);assert.equal(new Set(finished).size,12,'Four workers do not double-process listings');
let clock=0,attempts=0;
await previewWorkers(Array.from({length:600}),async()=>{attempts++;clock++},{concurrency:1,deadline:500,now:()=>clock});
assert.equal(attempts,500,'Time budget can process more than the former 240-entry cap');
const folder=await mkdtemp(tmpdir()+'/reposhelf-backfill-');
try{const file=pathToFileURL(folder+'/catalog.json'),snapshots=[{repositories:[base]}];const persist=checkpointWriter([file],snapshots,{interval:10000,now:()=>clock});
const first=persist();snapshots[0].repositories=[good];await persist(true);await first;
assert.equal(JSON.parse(await readFile(file,'utf8')).repositories[0].demoHealth.status,'working','Newer queued progress wins');
}finally{await rm(folder,{recursive:true,force:true})}
console.log('Browser backfill, retry isolation, time budgets and durable progress passed.');
